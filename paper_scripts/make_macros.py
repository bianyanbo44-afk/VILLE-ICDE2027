"""LaTeX macros for every aggregate number quoted in the text that depends on the set of queries.
Run: python -I make_macros.py <results_dir> <out.tex>"""
import sys, os, json
import numpy as np
from scipy.stats import spearmanr

RES, OUT = sys.argv[1], sys.argv[2]


def load(name):
    p = os.path.join(RES, name)
    return {k: v for k, v in json.load(open(p)).items() if not k.startswith('_')} if os.path.exists(p) else {}


def gm(x):
    x = [v for v in x if v > 0]
    return float(np.exp(np.mean(np.log(x))))


def ratio(S, b, ref='BET-P'):
    return gm([v['summary'][b]['cost'] / v['summary'][ref]['cost'] for v in S.values()])


def thou(n):
    return f'{int(n):,}'.replace(',', '{,}')


D1, D2, D3 = load('d1_main.json'), load('d2_wor.json'), load('d3_arxiv.json')
ALL = {**{'S:' + k: v for k, v in D1.items()}, **{'L:' + k: v for k, v in D2.items()}, **{'A:' + k: v for k, v in D3.items()}}
LLM = {**{'L:' + k: v for k, v in D2.items()}, **{'A:' + k: v for k, v in D3.items()}}
R = 30
M = {}
M['NQ'] = str(len(ALL)); M['NQS'] = str(len(D1)); M['NQL'] = str(len(D2)); M['NQA'] = str(len(D3))
M['NQLLM'] = str(len(LLM)); M['NEXEC'] = thou(R * len(ALL))
for tag, S in (('', ALL), ('AX', D3), ('LLM', LLM), ('AMZL', D2), ('AMZS', D1)):
    M[tag + 'RWSR'] = f"{ratio(S, 'WSR'):.1f}"; M[tag + 'RBSP'] = f"{ratio(S, 'BS-P'):.1f}"
    M[tag + 'RHS'] = f"{ratio(S, 'HS'):.1f}"; M[tag + 'RBET'] = f"{ratio(S, 'BET'):.1f}"
    M[tag + 'RCLTP'] = f"{ratio(S, 'CLT-P'):.2f}"; M[tag + 'RCLT'] = f"{ratio(S, 'CLT'):.2f}"
    M[tag + 'PROXYEFF'] = f"{ratio(S, 'WSR') / ratio(S, 'WSR-P'):.1f}"        # Evergreen-CS -> Evergreen-CS+P
    M[tag + 'BOUNDEFF'] = f"{ratio(S, 'WSR-P'):.1f}"                          # Evergreen-CS+P -> VILLE
    M[tag + 'BETVSWSR'] = f"{ratio(S, 'WSR') / ratio(S, 'BET'):.1f}"           # Evergreen-CS vs VILLE-P
M['RCLTPINV'] = f"{1 / ratio(ALL, 'CLT-P'):.1f}"
M['RWSRMAX'] = f"{max(v['summary']['WSR']['cost'] / v['summary']['BET-P']['cost'] for v in ALL.values()):.1f}"
M['AXRWSRMAX'] = f"{max(v['summary']['WSR']['cost'] / v['summary']['BET-P']['cost'] for v in D3.values()):.1f}"
for g, nm in (('year', 'AXYEAR'), ('area', 'AXAREA')):
    S = {k: v for k, v in D3.items() if k.startswith(g + '|')}
    M[nm + 'RWSR'] = f"{ratio(S, 'WSR'):.1f}"; M[nm + 'RHS'] = f"{ratio(S, 'HS'):.1f}"
M['NLEWSR'] = str(sum(v['summary']['BET-P']['cost'] <= v['summary']['WSR']['cost'] + 1e-12 for v in ALL.values()))
M['NLEBSP'] = str(sum(v['summary']['BET-P']['cost'] <= v['summary']['BS-P']['cost'] + 1e-12 for v in ALL.values()))
M['NLEHS'] = str(sum(v['summary']['BET-P']['cost'] <= v['summary']['HS']['cost'] + 1e-12 for v in ALL.values()))
# savings vs mean group size
gs = np.array([v['N'] / v['K'] for v in ALL.values()])
rw = np.array([v['summary']['WSR']['cost'] / v['summary']['BET-P']['cost'] for v in ALL.values()])
M['RHOGS'] = f"{spearmanr(gs, rw)[0]:.2f}"
for nm, lo, hi in (('BINA', 0, 5e3), ('BINB', 5e3, 5e4), ('BINC', 5e4, 1e12)):
    sel = (gs >= lo) & (gs < hi)
    M[nm] = f"{np.exp(np.log(rw[sel]).mean()):.1f}"; M[nm + 'N'] = str(int(sel.sum()))
# validity
errs = {m: int(round(sum(v['summary'][m]['answer_err'] * R for v in ALL.values()))) for m in ('CLT', 'CLT-P', 'BET-P')}
M['NCLTERR'] = str(errs['CLT']); M['NCLTPERR'] = str(errs['CLT-P'])
M['NCLTERRQ'] = str(sum(v['summary']['CLT']['answer_err'] > 0 for v in ALL.values()))
M['NCLTPERRQ'] = str(sum(v['summary']['CLT-P']['answer_err'] > 0 for v in ALL.values()))
assert errs['BET-P'] == 0
# run-to-run spread of VILLE's cost
cv = {tag: [v['summary']['BET-P']['cost_sd'] / v['summary']['BET-P']['cost'] for v in S.values() if 'cost_sd' in v['summary']['BET-P']]
      for tag, S in (('S', D1), ('L', D2), ('A', D3))}
allcv = sum(cv.values(), [])
if allcv:
    M['CVMED'] = f"{100 * np.median(allcv):.0f}"; M['CVMAX'] = f"{100 * max(allcv):.0f}"; M['NCV'] = str(len(allcv))
    M['CVSEMAX'] = f"{100 * max(allcv) / np.sqrt(R):.1f}"                 # relative standard error of a 30-run mean
# LLM calls the proxy saves per LLM-judged predicate (VILLE-P minus VILLE, summed over that predicate's queries)
sav = {}
for tag, S in (('L', D2), ('A', D3)):
    for k, v in S.items():
        key = (tag, k.split('|')[1])
        sav[key] = sav.get(key, 0.0) + v['N'] * (v['summary']['BET']['cost'] - v['summary']['BET-P']['cost'])
if sav:
    M['PROXYSAVEMIN'] = f"{min(sav.values()) / 1000:.0f}"; M['PROXYSAVEMAX'] = f"{max(sav.values()) / 1000:.0f}"
# proxy-only answers
po = json.load(open(os.path.join(RES, 'proxy_only.json')))
po = {k: v for k, v in po.items() if (k[0] == 'S' and k[2:] in D1) or (k[0] == 'L' and k[2:] in D2) or (k[0] == 'A' and k[2:] in D3)}
M['NPROXYWRONG'] = str(sum(v[0] for v in po.values())); M['NPROXYQ'] = str(len(po))
lines = ['% generated by make_macros.py; do not edit'] + [f'\\newcommand{{\\num{k}}}{{{v}}}' for k, v in sorted(M.items())]
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('\n'.join(lines))
